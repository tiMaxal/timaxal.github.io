/**
 * Basic HTML to Markdown converter
 * This is a simple extractor, not perfect conversion
 */
function htmlToMarkdown(html, title, outputPath) {
  // Extract just the content between <div class="container"> tags
  const containerMatch = html.match(/<div class="container">([\s\S]*?)<div id="footer-container">/);
  let content = containerMatch ? containerMatch[1] : html;
  
  // Remove HTML comments
  content = content.replace(/<!--[\s\S]*?-->/g, '');
  
  // Convert headings
  content = content.replace(/<h1[^>]*>(.*?)<\/h1>/gi, '\n# $1\n');
  content = content.replace(/<h2[^>]*>(.*?)<\/h2>/gi, '\n## $1\n');
  content = content.replace(/<h3[^>]*>(.*?)<\/h3>/gi, '\n### $1\n');
  content = content.replace(/<h4[^>]*>(.*?)<\/h4>/gi, '\n#### $1\n');
  
  // Convert paragraphs
  content = content.replace(/<p[^>]*>(.*?)<\/p>/gis, '\n$1\n');
  
  // Convert links
  content = content.replace(/<a[^>]*href=["']([^"']+)["'][^>]*>(.*?)<\/a>/gi, '[$2]($1)');
  
  // Convert images
  content = content.replace(/<img[^>]*src=["']([^"']+)["'][^>]*alt=["']([^"']*)["'][^>]*>/gi, '![$2]($1)');
  
  // Convert lists
  content = content.replace(/<li[^>]*>(.*?)<\/li>/gis, '- $1');
  content = content.replace(/<ul[^>]*>/gi, '\n');
  content = content.replace(/<\/ul>/gi, '\n');
  content = content.replace(/<ol[^>]*>/gi, '\n');
  content = content.replace(/<\/ol>/gi, '\n');
  
  // Convert strong/bold
  content = content.replace(/<strong[^>]*>(.*?)<\/strong>/gi, '**$1**');
  content = content.replace(/<b[^>]*>(.*?)<\/b>/gi, '**$1**');
  
  // Convert em/italic
  content = content.replace(/<em[^>]*>(.*?)<\/em>/gi, '*$1*');
  content = content.replace(/<i[^>]*>(.*?)<\/i>/gi, '*$1*');
  
  // Convert code
  content = content.replace(/<code[^>]*>(.*?)<\/code>/gi, '`$1`');
  
  // Convert br to newlines
  content = content.replace(/<br\s*\/?>/gi, '\n');
  
  // Remove remaining HTML tags (divs, spans, etc.)
  content = content.replace(/<div[^>]*>/gi, '\n');
  content = content.replace(/<\/div>/gi, '\n');
  content = content.replace(/<span[^>]*>/gi, '');
  content = content.replace(/<\/span>/gi, '');
  
  // Clean up whitespace
  content = content.replace(/\n{3,}/g, '\n\n');
  content = content.trim();
  
  // Create frontmatter
  const frontmatter = `---
title: ${title}
path: ${outputPath}
---

`;

  return frontmatter + content;
}

/**
 * Convert a single HTML file to markdown template
 */
function convertPage(htmlRelPath, mdRelPath, title) {
  const htmlPath = path.join(__dirname, '..', htmlRelPath);
  const mdPath = path.join(MD_BAK_DIR, mdRelPath);
  
  console.log(`📄 Converting: ${htmlRelPath}`);
  
  if (!fs.existsSync(htmlPath)) {
    console.log(`   ⚠️  HTML file not found, skipping`);
    return false;
  }
  
  try {
    // Read HTML
    const html = fs.readFileSync(htmlPath, 'utf-8');
    
    // Convert to markdown
    const outputPath = htmlRelPath.replace(/^HTML\//, '');
    const markdown = htmlToMarkdown(html, title, outputPath);
    
    // Create output directory
    const mdDir = path.dirname(mdPath);
    if (!fs.existsSync(mdDir)) {
      fs.mkdirSync(mdDir, { recursive: true });
    }
    
    // Write markdown file
    fs.writeFileSync(mdPath, markdown, 'utf-8');
    console.log(`   ✅ Created: ${mdRelPath}`);
    return true;
  } catch (error) {
    console.log(`   ❌ Error: ${error.message}`);
    return false;
  }
}

/**
 * Main function
 */
function main() {
  console.log('📝 HTML to Markdown Template Creator\n');
  console.log('⚠️  NOTE: These are REFERENCE templates only!');
  console.log('   Saved to: site-helpers/md/md-bak/');
  console.log('   Not processed by build system.\n');
  
  // Create md-bak directory
  if (!fs.existsSync(MD_BAK_DIR)) {
    fs.mkdirSync(MD_BAK_DIR, { recursive: true });
  }
  
  // Create README in md-bak
  const readmePath = path.join(MD_BAK_DIR, 'README.md');
  const readme = `# Markdown Templates (md-bak)

This directory contains **REFERENCE templates** only.

## Purpose

These .md files are converted from existing HTML pages to serve as:
- 📋 Reference for content structure
- 🔄 Templates if you want to convert a page to markdown workflow
- 💾 Backup of page content in markdown format

## Important

⚠️ **Files in this directory are NOT processed by the build system!**

- These files are ignored by md-to-html.js
- They will NOT generate/update HTML pages
- They are for REFERENCE ONLY

## Usage

**To convert a page to markdown workflow:**

1. Copy the .md file from md-bak/ to md/
2. Edit the content as needed
3. Run build script: \`node md-to-html.js --all\`
4. The HTML will be regenerated from markdown

**Example:**
\`\`\`bash
# Copy template
cp site-helpers/md-bak/software/software.md site-helpers/md/software/software.md

# Edit content
nano site-helpers/md/software/software.md

# Build
cd site-mng
node md-to-html.js --all

# Result: HTML/software/software.html regenerated from markdown
\`\`\`

## Excluded Pages

These pages were NOT converted (too complex or generated):
- index.html - Root page, complex layout
- donate.html - Complex payment widgets
- hns-pf.html - Generated by hns-portfolio-maker.py
- hmartld.html - Possibly generated/complex

---

*Templates auto-generated from HTML files*
*For workflow details, see: ../site-mng/MARKDOWN-WORKFLOW.md*
`;
  
  fs.writeFileSync(readmePath, readme, 'utf-8');
  console.log('📄 Created README.md in md-bak/\n');
  
  // Convert pages
  let converted = 0;
  let skipped = 0;
  
  for (const page of PAGES_TO_CONVERT) {
    if (convertPage(page.html, page.md, page.title)) {
      converted++;
    } else {
      skipped++;
    }
  }
  
  console.log(`\n✅ Conversion complete!`);
  console.log(`   Converted: ${converted}`);
  console.log(`   Skipped: ${skipped}`);
  console.log(`\n💡 Next steps:`);
  console.log(`   1. Review templates in: ${MD_BAK_DIR}`);
  console.log(`   2. To use: Copy from md-bak/ to md/`);
  console.log(`   3. Edit and run: node md-to-html.js --all\n`);
}

// Run
if (require.main === module) {
  main();
}

module.exports = { htmlToMarkdown, convertPage };
